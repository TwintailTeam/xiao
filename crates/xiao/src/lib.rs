fn match_compositor_gpu() {
    if !cfg!(target_os = "linux") || !config::match_gpu() {
        return;
    }
    let wayland = std::env::var_os("WAYLAND_DISPLAY").is_some() || std::env::var("XDG_SESSION_TYPE").is_ok_and(|session| session == "wayland");
    let platform = std::env::var("QT_QPA_PLATFORM").unwrap_or_default();
    if !wayland || !(platform.is_empty() || platform.starts_with("wayland")) {
        return;
    }
    let flags = std::env::var("QTWEBENGINE_CHROMIUM_FLAGS").unwrap_or_default();
    if flags.contains("--render-node-override") {
        return;
    }
    let Some(node) = owned_c_str(unsafe { ffi::compositor_render_node() }) else { return };
    app::trace!("[gpu] QtWebEngine will allocate on {node}, the GPU the compositor renders with");
    let flag = format!("--render-node-override={node}");
    let flags = if flags.trim().is_empty() { flag } else { format!("{flags} {flag}") };
    unsafe { std::env::set_var("QTWEBENGINE_CHROMIUM_FLAGS", flags) };
}

fn close_remote_debugging() {
    if cfg!(debug_assertions) {
        return;
    }
    unsafe { std::env::remove_var("QTWEBENGINE_REMOTE_DEBUGGING") };

    if let Ok(flags) = std::env::var("QTWEBENGINE_CHROMIUM_FLAGS") {
        let kept: Vec<&str> = flags.split_whitespace().filter(|flag| !flag.starts_with("--remote-debugging")).collect();
        unsafe { std::env::set_var("QTWEBENGINE_CHROMIUM_FLAGS", kept.join(" ")) };
    }
}

