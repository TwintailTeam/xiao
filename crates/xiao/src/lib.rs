fn owned_c_str(raw: *mut std::os::raw::c_char) -> Option<String> {
    if raw.is_null() {
        return None;
    }
    let owned = unsafe { std::ffi::CStr::from_ptr(raw) }.to_string_lossy().into_owned();
    unsafe { ffi::string_free(raw) };
    Some(owned)
}

pub(crate) fn notify(title: &str, body: &str) -> bool {
    let (Ok(app), Ok(title), Ok(body)) = (std::ffi::CString::new(config::product_name()), std::ffi::CString::new(title), std::ffi::CString::new(body)) else {
        return false;
    };
    unsafe { ffi::notify(app.as_ptr(), title.as_ptr(), body.as_ptr()) }
}

fn with_c_str<R>(value: &str, use_it: impl FnOnce(*const std::os::raw::c_char) -> R) -> Option<R> {
    std::ffi::CString::new(value).ok().map(|owned| use_it(owned.as_ptr()))
}
